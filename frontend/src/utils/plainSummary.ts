// 기록 목록의 요약(summary)은 백엔드가 답 본문의 공백만 정리해 앞부분을 자른 값이라 마크다운 기호가 그대로 들어 있다
// ("## 주가 동향 SK하이닉스의 …", 2026-11-20 최종 브라우저 검증). 목록 한 줄 미리보기에서는 제목 기호(#)·강조(**, __)·
// 코드(`)·인용(>) 기호만 뗀다. 글자와 숫자, 번호 목록("1.")은 그대로 둔다. 이미 저장된 기록에도 적용되도록 화면에서 처리한다.
export function plainSummary(summary: string): string {
  return summary
    .replace(/(^|\s)#{1,6}(?=\s)/g, '$1')
    .replace(/(^|\s)>(?=\s)/g, '$1')
    .replace(/\*\*|__|`/g, '')
    .replace(/\s{2,}/g, ' ')
    .trim()
}
