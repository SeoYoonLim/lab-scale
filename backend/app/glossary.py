# 정의가 아니라 판단·조회를 묻는 표현(이런 질문은 기존 흐름): "PER이 높으면 좋아?", "PER 몇 배면 싸?"
_NOT_DEFINITION_RE = re.compile(
    r"얼마|몇|높|낮|좋|나쁘|싸|비싸|순위|추천|비교|어때|오늘|요즘|최근|지금|현재|전망|종목|(?<![가-힣])주가(?!수익|순자산)|시세|왜|이유|어떤\s*게|차이"
)
_ASCII = re.compile(r"[A-Za-z0-9]")

_ALIAS_INDEX = sorted(((alias, term) for term, (aliases, _) in GLOSSARY.items() for alias in aliases),
                      key=lambda x: -len(x[0]))


def find_term(question: str) -> str | None:
    """질문에 나온 사전 용어(표제어). 긴 별칭부터 찾는다. 영문 별칭은 앞뒤가 영문/숫자가 아닐 때만."""
    q = question or ""
    low = q.casefold()
    for alias, term in _ALIAS_INDEX:
        a = alias.casefold()
        for m in re.finditer(re.escape(a), low):
            st, en = m.span()
            if _ASCII.match(a[0]) and st > 0 and _ASCII.match(low[st - 1]):
                continue
            if _ASCII.match(a[-1]) and en < len(low) and _ASCII.match(low[en]):
                continue
            return term
    return None


_UNKNOWN_TERM_RE = re.compile(
    r"^\s*(?P<term>[^\s?]{1,12}(?:\s[^\s?]{1,12})?)\s*(?:이|가|은|는|란|이란|라는\s*(?:게|건|것은?))?\s*"
    r"(?:뭐야|뭐예요|뭐에요|뭔가요|뭐지|뭐임|뭐냐|무엇인가요|무엇이야|무엇이에요|뭘까|무슨\s*뜻|무슨\s*의미|뜻이\s*뭐|의미가\s*뭐|뭔지)"
)


